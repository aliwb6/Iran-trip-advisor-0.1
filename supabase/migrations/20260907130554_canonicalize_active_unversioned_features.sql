-- Canonicalize active features that previously existed only as unversioned/manual SQL.

-- 1) Custom AI trip drafts used by TripBuilder.
CREATE TABLE IF NOT EXISTS public.custom_trips (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  trip_data jsonb NOT NULL,
  status text NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT custom_trips_status_check CHECK (status IN ('draft','saved','booked','completed'))
);

CREATE INDEX IF NOT EXISTS idx_custom_trips_user_id ON public.custom_trips(user_id);
CREATE INDEX IF NOT EXISTS idx_custom_trips_status ON public.custom_trips(status);
CREATE INDEX IF NOT EXISTS idx_custom_trips_created_at ON public.custom_trips(created_at DESC);

ALTER TABLE public.custom_trips ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "custom_trips_select_own" ON public.custom_trips;
DROP POLICY IF EXISTS "custom_trips_insert_own" ON public.custom_trips;
DROP POLICY IF EXISTS "custom_trips_update_own" ON public.custom_trips;
DROP POLICY IF EXISTS "custom_trips_delete_own" ON public.custom_trips;
DROP POLICY IF EXISTS "Users can view their own trips" ON public.custom_trips;
DROP POLICY IF EXISTS "Users can create their own trips" ON public.custom_trips;
DROP POLICY IF EXISTS "Users can update their own trips" ON public.custom_trips;
DROP POLICY IF EXISTS "Users can delete their own trips" ON public.custom_trips;

CREATE POLICY "custom_trips_select_own"
  ON public.custom_trips FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));
CREATE POLICY "custom_trips_insert_own"
  ON public.custom_trips FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY "custom_trips_update_own"
  ON public.custom_trips FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY "custom_trips_delete_own"
  ON public.custom_trips FOR DELETE TO authenticated
  USING (user_id = (SELECT auth.uid()));

REVOKE ALL ON TABLE public.custom_trips FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.custom_trips TO authenticated;

DROP TRIGGER IF EXISTS trg_custom_trips_updated_at ON public.custom_trips;
CREATE TRIGGER trg_custom_trips_updated_at
  BEFORE UPDATE ON public.custom_trips
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


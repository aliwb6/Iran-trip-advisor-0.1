DROP POLICY IF EXISTS "homepage_destinations_public_active" ON public.homepage_destinations;
DROP POLICY IF EXISTS "homepage_destinations_admin_all" ON public.homepage_destinations;

CREATE POLICY "homepage_destinations_public_active"
  ON public.homepage_destinations FOR SELECT TO anon, authenticated
  USING (is_active IS TRUE);

CREATE POLICY "homepage_destinations_admin_all"
  ON public.homepage_destinations FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND (p.is_admin IS TRUE OR p.role = 'admin')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND (p.is_admin IS TRUE OR p.role = 'admin')
    )
  );

GRANT SELECT ON TABLE public.homepage_destinations TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.homepage_destinations TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.homepage_destinations_id_seq TO authenticated;


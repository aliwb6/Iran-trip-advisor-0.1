CREATE TRIGGER trg_homepage_destinations_updated_at
  BEFORE UPDATE ON public.homepage_destinations
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 3) Canonical proposal rejection RPC for the tourist/request owner.
CREATE OR REPLACE FUNCTION public.reject_trip_proposal(proposal_id uuid)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.trip_slots AS slot
    JOIN public.trip_requests AS request
      ON request.id = slot.trip_request_id
    WHERE slot.id = proposal_id
      AND request.user_id = (SELECT auth.uid())
      AND slot.status NOT IN ('rejected', 'finalized', 'selected', 'closed')
  ) THEN
    RAISE EXCEPTION 'Not authorized to reject this proposal';
  END IF;

  UPDATE public.trip_slots AS slot
  SET status = 'rejected'
  WHERE slot.id = proposal_id
    AND slot.status NOT IN ('rejected', 'finalized', 'selected', 'closed');

  RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION public.reject_trip_proposal(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.reject_trip_proposal(uuid) TO authenticated;

